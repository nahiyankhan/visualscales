test('links grow from the selection, branch after their first hop, and do not replay when panning', async ({ page }) => {
  await page.goto('/globe.html')
  await page.getByRole('searchbox').fill('palette.indigo.600')
  await page.getByRole('button', { name: /palette.indigo.600 ·/ }).click()
  await page.waitForFunction(() => document.querySelector('.relationship-connectors > g > path')?.getAnimations().length)
  const states = await page.locator('.relationship-connectors > g > path').evaluateAll(paths => paths.map(path => {
    const animation = path.getAnimations()[0]
    animation?.pause()
    return { source: (path as SVGPathElement).dataset.source, timing: animation?.effect?.getTiming(), direction: (path as SVGPathElement).dataset.revealDirection }
  }))
  const direct = states.find(state => state.source === 'palette.indigo.600')!
  const branch = states.find(state => state.source === 'semantic.focus.ring')!
  expect(direct.timing?.delay).toBe(0)
  expect(branch.timing?.delay).toBe(220)
  expect(direct.direction).toBe('source-to-target')
  await page.locator('.relationship-connectors > g > path').evaluateAll(paths => {
    paths.forEach(path => { (path as SVGPathElement & { testIdentity?: boolean }).testIdentity = true })
  })
  await page.mouse.move(600, 500)
  await page.mouse.wheel(100, 80)
  expect(await page.locator('.relationship-connectors > g > path').evaluateAll(paths => paths.every(path => (path as SVGPathElement & { testIdentity?: boolean }).testIdentity))).toBe(true)
  await page.keyboard.press('Escape')
  await settle(page)
  await expect(page.locator('.relationship-connectors > g > path')).toHaveCount(0)
})

test('modified wheel zoom anchors the pointer and regular scroll still pans without changing the collection', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/globe.html')
  await page.getByRole('button', { name: 'Relationships', exact: true }).click()
  const grid = page.locator('.surface-grid')
  const before = JSON.parse((await grid.getAttribute('data-network-cards'))!)
  const collection = await grid.getAttribute('data-position')
  const scale = Number(await grid.getAttribute('data-network-scale'))
  const prevented = await page.locator('.surface-viewport').evaluate(surface => !surface.dispatchEvent(new WheelEvent('wheel', { clientX: 500, clientY: 400, deltaY: -30, ctrlKey: true, cancelable: true, bubbles: true })))
  expect(prevented).toBe(true)
  const nextScale = Number(await grid.getAttribute('data-network-scale'))
  expect(nextScale).toBeGreaterThan(scale)
  const after = JSON.parse((await grid.getAttribute('data-network-cards'))!)
  const anchor = { x: 500 - 720, y: 400 - 500 }
  expect((anchor.x - after[0].x) / nextScale).toBeCloseTo((anchor.x - before[0].x) / scale)
  expect((anchor.y - after[0].y) / nextScale).toBeCloseTo((anchor.y - before[0].y) / scale)
  await page.mouse.move(500, 400)
  await page.mouse.wheel(100, 80)
  expect(Number(await grid.getAttribute('data-network-scale'))).toBe(nextScale)
  await expect(grid).toHaveAttribute('data-position', collection!)
  const animations = await page.locator('.relationship-connectors > g > path').evaluateAll(paths => paths.flatMap(path => path.getAnimations()))
  expect(animations).toHaveLength(0)
})

test('two-finger touch pinch zooms the network, does not select a card, then hands off to one-finger pan', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/globe.html')
  await page.getByRole('button', { name: 'Relationships', exact: true }).click()
  const grid = page.locator('.surface-grid')
  const scale = Number(await grid.getAttribute('data-network-scale'))
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 120, y: 420, id: 1 }, { x: 240, y: 420, id: 2 }] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 80, y: 420, id: 1 }, { x: 280, y: 420, id: 2 }] })
  await expect.poll(async () => Number(await grid.getAttribute('data-network-scale'))).toBeGreaterThan(scale)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [{ x: 280, y: 420, id: 2 }] })
  const cards = await grid.getAttribute('data-network-cards')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 100, y: 440, id: 1 }] })
  await expect(grid).not.toHaveAttribute('data-network-cards', cards!)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(grid).toHaveAttribute('data-selected', '')
  await cdp.detach()
})

