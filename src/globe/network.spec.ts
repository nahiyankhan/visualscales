  for (const card of cards) expect(visible.filter(id => id === card.id)).toHaveLength(1)
  await expect(page.locator('[data-source="palette.indigo.600"][data-target="semantic.action.primary.background"]')).toHaveCount(1)
  await expect(page.locator('[data-source="semantic.focus.ring"][data-target="component.switch.focus"]')).toHaveCount(1)
