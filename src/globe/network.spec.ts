test('shared zoom controls reflect gesture changes and disable both graph limits', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/globe.html')
  await page.getByRole('button', { name: 'Relationships', exact: true }).click()
  const grid = page.locator('.surface-grid')
  const percentage = page.locator('.surface-zoom-reset')
  await expect(percentage).toHaveText('100%')
  await page.locator('.surface-viewport').evaluate(surface => {
    const wheel = (deltaY: number, count: number) => {
      for (let i = 0; i < count; i++) surface.dispatchEvent(new WheelEvent('wheel', { clientX: 180, clientY: 400, deltaY, altKey: true, cancelable: true, bubbles: true }))
    }
    wheel(-1000, 5)
  })
  await expect(grid).toHaveAttribute('data-network-scale', '3.5')
  await expect(percentage).toHaveText('461%')
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Zoom out', exact: true })).toBeEnabled()
  await page.locator('.surface-viewport').evaluate(surface => {
    for (let i = 0; i < 10; i++) surface.dispatchEvent(new WheelEvent('wheel', { clientX: 180, clientY: 400, deltaY: 1000, ctrlKey: true, cancelable: true, bubbles: true }))
  })
  await expect(grid).toHaveAttribute('data-network-scale', '0.005')
  await expect(percentage).toHaveText('1%')
  await expect(page.getByRole('button', { name: 'Zoom out', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toBeEnabled()
  await percentage.click()
  await expect(page.getByRole('button', { name: 'Zoom out', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Zoom in', exact: true })).toBeEnabled()
  const fitScale = Number(await grid.getAttribute('data-network-scale'))
  await expect(percentage).toHaveText(`${Math.round(fitScale / .76 * 100)}%`)
  await page.getByRole('button', { name: 'Back to collection', exact: true }).click()
  await expect(percentage).toHaveText('100%')
  await expect(percentage).toHaveAccessibleName('Reset zoom (100%)')
})

