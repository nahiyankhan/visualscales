  await expect(page.locator('.relationship-connectors marker')).toHaveCount(0)
  await expect(page.locator('.relationship-connectors mask g rect')).toHaveCount(218)
  const paths = await page.locator('.relationship-connectors > g > path').evaluateAll(paths => paths.map(path => path.getAttribute('d')))
  expect(paths.every(path => path && !path.includes('C'))).toBe(true)
  expect(paths.some(path => path?.includes('Q'))).toBe(true)
